"use client";
import { useActionState, useState, useTransition } from "react";
import { Loader2, ShieldCheck } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { confirmAdminMfaSetup, startAdminMfaSetup, verifyAdminCode, type MfaFormState, type MfaSetup } from "@/lib/auth/mfa-actions";

function CodeInput() {
  return (
    <div className="space-y-2">
      <Label htmlFor="code">6-digit code</Label>
      <Input id="code" name="code" inputMode="numeric" autoComplete="one-time-code" pattern="[0-9]{6}" maxLength={6} required autoFocus
        className="text-center font-mono text-2xl tracking-[0.4em]" />
    </div>
  );
}

function Alert({ text }: { text?: string }) {
  return text ? <p role="alert" className="rounded-md bg-destructive/5 p-3 text-sm text-destructive">{text}</p> : null;
}

export function MfaVerifyForm({ next }: { next: string }) {
  const [state, action, pending] = useActionState<MfaFormState, FormData>(verifyAdminCode, {});
  return (
    <form action={action} className="space-y-4">
      <input type="hidden" name="next" value={next} />
      <CodeInput />
      <Alert text={state.error} />
      <Button type="submit" className="w-full" size="lg" disabled={pending}>
        {pending ? <Loader2 className="animate-spin" /> : <ShieldCheck />} Verify
      </Button>
      <p className="text-xs text-muted-foreground">Lost your phone? Ask a Super Admin to reset your two-step login (Admin → Staff).</p>
    </form>
  );
}

export function MfaSetupForm({ next }: { next: string }) {
  const [setup, setSetup] = useState<MfaSetup | null>(null);
  const [starting, start] = useTransition();
  const [state, action, pending] = useActionState<MfaFormState, FormData>(confirmAdminMfaSetup, {});

  if (!setup?.ok) {
    return (
      <div className="space-y-4">
        <ol className="list-decimal space-y-1 pl-5 text-sm">
          <li>Install <strong>Google Authenticator</strong> or <strong>Microsoft Authenticator</strong> on your phone (free).</li>
          <li>Click the button below and scan the QR code with the app.</li>
          <li>Type the 6-digit code the app shows.</li>
        </ol>
        <Alert text={setup && !setup.ok ? setup.error : undefined} />
        <Button type="button" className="w-full" size="lg" disabled={starting} onClick={() => start(async () => setSetup(await startAdminMfaSetup()))}>
          {starting && <Loader2 className="animate-spin" />} Set up two-step login
        </Button>
      </div>
    );
  }
  return (
    <form action={action} className="space-y-4">
      <input type="hidden" name="next" value={next} />
      <input type="hidden" name="factorId" value={setup.factorId} />
      <p className="text-sm">Scan this QR code with your authenticator app:</p>
      {/* eslint-disable-next-line @next/next/no-img-element -- data: URI generated by Supabase */}
      <img src={setup.qr} alt="QR code for your authenticator app" width={200} height={200} className="mx-auto rounded-lg border bg-white p-2" />
      <details className="text-sm">
        <summary className="cursor-pointer text-primary">Can’t scan? Enter this key instead</summary>
        <p className="mt-2 rounded-md bg-muted p-2 text-center font-mono break-all select-all">{setup.secret}</p>
      </details>
      <CodeInput />
      <Alert text={state.error} />
      <Button type="submit" className="w-full" size="lg" disabled={pending}>
        {pending ? <Loader2 className="animate-spin" /> : <ShieldCheck />} Turn on two-step login
      </Button>
    </form>
  );
}
