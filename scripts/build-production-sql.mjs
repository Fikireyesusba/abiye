#!/usr/bin/env node
/**
 * Builds supabase/production-setup.sql: every migration (in order) + the
 * category starter, in ONE transaction, for pasting into the Supabase SQL
 * Editor (no CLI needed). Re-run after adding a migration: npm run db:bundle
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "supabase/migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const q = (s) => `'${s.replace(/'/g, "''")}'`;

const parts = [
  `-- =============================================================================
-- ABIYE — PRODUCTION DATABASE SETUP (generated by scripts/build-production-sql.mjs)
-- Paste ALL of this into Supabase → SQL Editor → New query → Run. Once only.
-- Contains: ${files.length} migrations + department/category starter.
-- No sample products, no bank details, no passwords.
-- Runs as ONE transaction: if anything fails, nothing is changed.
-- DO NOT EDIT BY HAND — regenerate with: npm run db:bundle
-- =============================================================================
begin;

do $guard$
begin
  if to_regclass('public.products') is not null then
    raise exception 'Abiye database is already set up (public.products exists). Nothing was changed.';
  end if;
end
$guard$;
`,
];

for (const f of files) {
  parts.push(`\n-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>> ${f}\n${readFileSync(join(dir, f), "utf8").trim()}\n`);
}

parts.push(`\n-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>> supabase/starter.sql\n${readFileSync(join(root, "supabase/starter.sql"), "utf8").replace(/\nselect department[^\n]*\n?$/, "\n").trim()}\n`);

// Record the migrations the way the Supabase CLI / GitHub integration does, so they are never re-applied.
parts.push(`
-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>> migration bookkeeping
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);
insert into supabase_migrations.schema_migrations (version, name) values
${files.map((f) => `  (${q(f.split("_")[0])}, ${q(f.replace(/^\d+_/, "").replace(/\.sql$/, ""))})`).join(",\n")}
on conflict (version) do nothing;

commit;

-- Result check (should list: cosmetics 6, electronics 7, printing 1)
select department, count(*) as categories from public.categories group by department order by department;
`);

writeFileSync(join(root, "supabase/production-setup.sql"), parts.join(""));
console.log(`supabase/production-setup.sql: ${files.length} migrations`);
